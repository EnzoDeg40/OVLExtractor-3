"""Capture RCT3's FlexiColour recolour table from the running Mac game and
write extractors/src/FlexiColourLut.inc.

The game builds, at start-up, a 32 swatch x 85 position table of BGRX colours
(position 41 is the pure swatch colour; 0-40 lighten it, 42-84 darken it).
A recolourable FlexiTexture's palette index i in band c (1-85, 86-170,
171-255) is drawn with table[swatch chosen for channel c][i - 1 - 85c]
(docs §3.8). On the Mac build (RCT3_Exe 3.3.4, build 204463) the table sits
at 0x100e43480 in __DATA; it was located by scanning for its first two
entries and is identical, byte for byte, to the table captured from the
Windows build (rerct3, FlexiColour_InitRecolorRampLUT @ 0x0101d7a0).

Usage (game running with rct3_saves' rct3probe injected, see its STARTUP.md):
    python3 scripts/capture_flexicolour_lut.py ../rct3_saves/tools/mac
"""
import sys
from pathlib import Path

ADDR, SWATCHES, RAMP = 0x100E43480, 32, 85


def main() -> None:
    sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else "../rct3_saves/tools/mac")
    import probe
    size = SWATCHES * RAMP * 4
    buf = b"".join(probe.read(ADDR + o, min(1024, size - o)) for o in range(0, size, 1024))
    write_inc(buf)


def write_inc(buf: bytes) -> None:
    out = Path(__file__).resolve().parent.parent / "extractors" / "src" / "FlexiColourLut.inc"
    lines = ["// GENERATED by scripts/capture_flexicolour_lut.py from the running game.",
             "// 32 swatches x 85 ramp positions, R, G, B. Position 41 = the pure swatch."]
    for s in range(SWATCHES):
        row = []
        for p in range(RAMP):
            b, g, r = buf[(s * RAMP + p) * 4: (s * RAMP + p) * 4 + 3]
            row.append(f"{r},{g},{b}")
        lines.append(f"/* {s:2d} */ " + ",".join(row) + ",")
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--from-file":
        write_inc(Path(sys.argv[2]).read_bytes())
    else:
        main()
